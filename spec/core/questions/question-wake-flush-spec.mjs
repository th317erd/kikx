'use strict';

/**
 * Regression coverage for the post-append flush barrier in
 * `QuestionAnswerService.deliverAnswer` (`src/core/questions/question-wake.mjs:208-216`).
 *
 * The service's stated guarantee is that an answer is durable *and dispatched*
 * before `submitAnswer` reports success. `appendUserMessage` alone does not give
 * that: the frame is queued, so a process that dies before the queue settles
 * loses the wake while the answer stays stored as `answered` — a question the
 * agent has been told was answered but never hears about.
 *
 * Mutation testing found this barrier had NO coverage: deleting both the
 * `frameRuntime.flush()` branch and the `frameStore?.flush?.()` fallback left the
 * original 12-test wake spec at 12/12 pass. These tests fail if it is removed.
 */

import assert from 'node:assert/strict';
import test from 'node:test';

import {
  QuestionAnswerService,
  QuestionsStore,
} from '../../../src/core/questions/index.mjs';

test('delivery awaits the runtime flush barrier before reporting success', async () => {
  let { service, runtime } = await setup();

  // The barrier must not have happened yet; it is what submission triggers.
  assert.equal(runtime.flushCalls, 0, 'flush must not run before an answer is submitted');

  let result = await service.submitAnswer('q_1', { answer: 'Postgres.', userID: 'user_1' });

  assert.equal(result.delivered, true);
  assert.equal(runtime.flushCalls, 1, 'delivery must flush the runtime exactly once');

  // The frame id is generated by the service, so pin it by identity rather
  // than by guessing: the reported id must be the frame actually appended.
  assert.equal(typeof result.frameID, 'string');
  assert.equal(runtime.appended.length, 1);
  assert.equal(result.frameID, runtime.appended[0].frame.id);
});

test('the flush barrier is awaited, not fired and forgotten', async () => {
  let { service, runtime } = await setup();

  // A manually-released gate: flush() does not settle until the test says so.
  // If the service dropped its `await`, submitAnswer would resolve while this
  // promise was still pending and `settled` would already be true.
  let release = null;
  runtime.flushGate = new Promise((resolve) => { release = resolve; });

  let settled = false;
  let submission = service.submitAnswer('q_1', { answer: 'Postgres.', userID: 'user_1' })
    .then((value) => {
      settled = true;
      return value;
    });

  // Give the microtask queue a chance to run; an awaited flush cannot complete.
  await new Promise((resolve) => setTimeout(resolve, 20));
  assert.equal(runtime.flushCalls, 1, 'flush must have been called');
  assert.equal(settled, false, 'submitAnswer resolved before the flush barrier settled');

  release();
  let result = await submission;

  assert.equal(settled, true);
  assert.equal(result.delivered, true);
});

test('an undeliverable answer does not flush (nothing was appended)', async () => {
  let { service, runtime } = await setup({ participantAgentIDs: [ 'someone_else' ] });

  let result = await service.submitAnswer('q_1', { answer: 'Postgres.', userID: 'user_1' });

  assert.equal(result.delivered, false);
  assert.equal(result.reason, 'agent-not-participant');
  assert.equal(runtime.appended.length, 0, 'no wake frame should be appended');
  assert.equal(runtime.flushCalls, 0, 'no barrier is needed when nothing was appended');

  // The answer itself is still durable — that is the data-loss guarantee.
  let stored = await service.questionsStore.getQuestion('q_1');
  assert.equal(stored.status, 'undeliverable');
  assert.equal(stored.answer, 'Postgres.');
});

test('a runtime without flush falls back to the store flush', async () => {
  let { service, runtime } = await setup({ omitRuntimeFlush: true });

  let result = await service.submitAnswer('q_1', { answer: 'Postgres.', userID: 'user_1' });

  assert.equal(result.delivered, true);
  assert.equal(runtime.storeFlushCalls, 1, 'store-level fallback must run when runtime.flush is absent');
});

async function setup({
  participantAgentIDs = [ 'agent_1' ],
  omitRuntimeFlush = false,
} = {}) {
  let questionsStore = createStore();
  await questionsStore.createQuestions({
    questions: [ { text: 'Which database should this use?' } ],
    mode: 'wait',
    sessionID: 'session_1',
    agentID: 'agent_1',
  });

  let runtime = createRuntime({ participantAgentIDs, omitRuntimeFlush });
  let service = new QuestionAnswerService({
    questionsStore,
    frameRuntime: runtime,
    logger: { warn() {}, error() {} },
  });

  return { service, runtime, questionsStore };
}

function createRuntime({ participantAgentIDs, omitRuntimeFlush }) {
  let runtime = {
    appended: [],
    flushCalls: 0,
    storeFlushCalls: 0,
    flushGate: null,
    async ensureSessionEntry(sessionID) {
      return { session: { id: sessionID, participantAgentIDs: [ ...participantAgentIDs ], deletedAt: null } };
    },
    async appendUserMessage(sessionID, input) {
      let frame = {
        id: input.id,
        type: 'UserMessage',
        sessionID,
        authorType: 'user',
        authorID: input.userID || null,
        hidden: false,
        deleted: false,
        content: { text: input.content.text, ...input.content },
      };

      if (input.targetAgentID)
        frame.targetAgentID = input.targetAgentID;

      if (input.continuation)
        frame.continuation = input.continuation;

      runtime.appended.push({ sessionID, input, frame });
      return { frame };
    },
    async flush() {
      runtime.flushCalls++;
      if (runtime.flushGate)
        await runtime.flushGate;
    },
    frameStore: {
      async flush() {
        runtime.storeFlushCalls++;
      },
    },
    emitRuntimeEvent() {},
  };

  if (omitRuntimeFlush)
    delete runtime.flush;

  return runtime;
}

function createStore() {
  let aeordb = createClient();
  let now = 1000;
  let ids = [ 'group_1', 'q_1' ];
  return new QuestionsStore({
    aeordb,
    clock: () => now++,
    idGenerator: () => ids.shift(),
  });
}

function createClient() {
  return {
    files: new Map(),
    async getFile(path) {
      if (!this.files.has(path)) {
        let error = new Error('Not found');
        error.status = 404;
        throw error;
      }

      return JSON.parse(JSON.stringify(this.files.get(path)));
    },
    async putFile(path, body) {
      this.files.set(path, JSON.parse(JSON.stringify(body)));
      return { path };
    },
    async deleteFile(path) {
      this.files.delete(path);
      return { path };
    },
    async list(path, options = {}) {
      let prefix = path.endsWith('/') ? path : `${path}/`;
      let glob = options.glob || null;
      let pattern = glob ? new RegExp(`^${glob.replace(/\./g, '\\.').replace(/\*/g, '[^/]*')}$`) : null;
      let items = [];

      for (let key of this.files.keys()) {
        if (!key.startsWith(prefix))
          continue;

        let rest = key.slice(prefix.length);
        if (rest.includes('/'))
          continue;

        if (pattern && !pattern.test(rest))
          continue;

        items.push({ path: key });
      }

      return { items, total: items.length, hasMore: false };
    },
  };
}
